use eyre::{Result, bail, eyre};
use url::Url;

use crate::config::Config;

const DEFAULT_ENDPOINT: &str = "http://localhost:8181";
const DEFAULT_ATTEMPT_TIMEOUT_MS: u64 = 3000;

/// The ordered daemon endpoints the popup will try, validated.
///
/// Unset -> `[http://localhost:8181]`. Every entry must be `http`, carry a
/// host, and have no path beyond `/`, no query, no fragment and no userinfo.
/// An empty list is an error, never a silent default. Render with
/// [`endpoint_base`] to get the form without the trailing `/`.
pub fn resolved_endpoints(config: &Config) -> Result<Vec<Url>> {
    log::debug!("extension::daemon::resolved_endpoints");
    let Some(raw) = &config.extension.endpoints else {
        return Ok(vec![
            Url::parse(DEFAULT_ENDPOINT).expect("DEFAULT_ENDPOINT is a valid URL"),
        ]);
    };
    if raw.is_empty() {
        bail!("extension.endpoints is empty; list at least one endpoint or remove the key");
    }
    raw.iter().map(|entry| parse_endpoint(entry)).collect()
}

/// Per-attempt timeout in milliseconds. Unset -> 3000; 0 is an error.
pub fn attempt_timeout_ms(config: &Config) -> Result<u64> {
    match config.extension.attempt_timeout_ms {
        None => Ok(DEFAULT_ATTEMPT_TIMEOUT_MS),
        Some(0) => bail!("extension.attempt-timeout-ms must be greater than 0"),
        Some(ms) => Ok(ms),
    }
}

/// The generated `daemon.js` text: the validated endpoint list and timeout the
/// popup bakes in. Both validators run here, plus the check that the manifest
/// permits every endpoint, so a bad `extension.*` config is a loud error before
/// anything is staged, shown or signed. Values go through `serde_json`, never
/// string formatting.
pub fn render_daemon_js(config: &Config) -> Result<String> {
    log::debug!("extension::daemon::render_daemon_js");
    let resolved = resolved_endpoints(config)?;
    ensure_permitted(config, &resolved)?;
    let endpoints: Vec<String> = resolved.iter().map(endpoint_base).collect();
    let timeout_ms = attempt_timeout_ms(config)?;
    Ok(format!(
        "// Generated by `sb borg extension stage` from borg.yml extension.*. Do not edit.\n\
         const BORG_DAEMON = Object.freeze({{\n  \
         endpoints: {},\n  \
         attemptTimeoutMs: {},\n}});\n",
        serde_json::to_string(&endpoints)?,
        serde_json::to_string(&timeout_ms)?,
    ))
}

/// Hex SHA-256 of the config-derived files `stage()` renders: `manifest.json`
/// with its `version` blanked, then `daemon.js`. Hashing the rendered output
/// covers every config input (`extension.*`, `server.host`) without listing
/// them. Each part is length-prefixed so the two cannot blur together.
pub fn baked_config_hash(config: &Config) -> Result<String> {
    use sha2::{Digest, Sha256};
    log::debug!("extension::daemon::baked_config_hash");
    let manifest = crate::extension::render_manifest("", config)?;
    let daemon_js = render_daemon_js(config)?;
    let mut hasher = Sha256::new();
    for part in [manifest, daemon_js] {
        hasher.update((part.len() as u64).to_be_bytes());
        hasher.update(part.as_bytes());
    }
    Ok(format!("{:x}", hasher.finalize()))
}

/// Every endpoint, the unset default included, must be permitted by the
/// manifest's final origin patterns; otherwise the extension ships unable to
/// reach it. An explicit `origin-patterns` with `endpoints` unset is the case
/// this catches: the default localhost endpoint is not added to that list.
fn ensure_permitted(config: &Config, endpoints: &[Url]) -> Result<()> {
    let patterns = crate::extension::manifest::origin_patterns(config);
    for endpoint in endpoints {
        let host = endpoint.host_str().unwrap_or_default();
        if !crate::extension::manifest::permits(&patterns, host) {
            bail!(
                "extension endpoint {} is not permitted by the manifest origin patterns {patterns:?}; \
                 set extension.endpoints to the daemon you reach, or add {host:?} to extension.origin-patterns",
                endpoint_base(endpoint)
            );
        }
    }
    Ok(())
}

/// An endpoint as the popup concatenates it with a path: no trailing `/`.
pub fn endpoint_base(endpoint: &Url) -> String {
    endpoint.as_str().trim_end_matches('/').to_string()
}

fn parse_endpoint(entry: &str) -> Result<Url> {
    let url = Url::parse(entry).map_err(|e| eyre!("extension.endpoints: {entry:?} is not a valid URL: {e}"))?;
    if url.scheme() != "http" {
        bail!(
            "extension.endpoints: {entry:?} must use http (host_permissions and the CSP are http-only), got {}",
            url.scheme()
        );
    }
    if url.host_str().is_none_or(str::is_empty) {
        bail!("extension.endpoints: {entry:?} has no host");
    }
    if url.path() != "/" {
        bail!("extension.endpoints: {entry:?} has a path; only a bare origin is allowed");
    }
    if url.query().is_some() {
        bail!("extension.endpoints: {entry:?} has a query string");
    }
    if url.fragment().is_some() {
        bail!("extension.endpoints: {entry:?} has a fragment");
    }
    if !url.username().is_empty() || url.password().is_some() {
        bail!("extension.endpoints: {entry:?} carries credentials; they would ship to AMO inside the .xpi");
    }
    Ok(url)
}

